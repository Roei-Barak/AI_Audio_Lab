// End-to-end against a running Lyra server (LYRA_ENGINE=mock is enough): upload → process → fix → MP4 → conflict → crash/retry.
// Usage: node e2e/server.cjs <clip.mp4> [outDir]   (server at LYRA_URL, default http://localhost:8443/)
const { chromium } = require('playwright');
const fs = require('fs');
const { execFileSync } = require('child_process');
const URL = process.env.LYRA_URL || 'http://localhost:8443/';
const CLIP = process.argv[2];
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ acceptDownloads: true, viewport: { width: 1440, height: 900 } });
  const pg = await ctx.newPage();
  const errs = [];
  let fails = 0;
  pg.on('pageerror', (e) => errs.push(e.message));
  const log = (k, v) => { if (!v) fails++; console.log((v ? 'PASS ' : 'FAIL ') + k); };
  await pg.goto(URL);
  await pg.evaluate(() => localStorage.clear());
  await pg.reload();
  await pg.getByText('שרת Lyra', { exact: false }).first().waitFor();
  log('server mode detected', true);
  await pg.getByRole('button', { name: /קובץ מקומי/ }).click();
  await pg.locator('input[type=file]').setInputFiles(CLIP);
  await pg.waitForTimeout(500);
  await pg.getByRole('button', { name: 'צור קריוקי' }).click();
  await pg.getByText('מייבא את השיר').waitFor();
  await pg.getByRole('heading', { name: 'בדיקה ותיקון מהיר' }).waitFor({ timeout: 90000 });
  log('processed on server, review opened', true);
  const first = pg.getByRole('button', { expanded: false }).filter({ hasText: /0:0/ }).first();
  await first.click();
  const chip = pg.locator('.chip').first();
  await chip.click();
  const wi = pg.getByLabel('מילה', { exact: true });
  await wi.fill('מתוקן'); await wi.press('Enter');
  await pg.getByText(/^נשמר בשרת ·/).waitFor({ timeout: 10000 });
  log('edit saved to server', true);
  const pid = await pg.evaluate(() => JSON.parse(localStorage.getItem('lyra.v1.project')).id);
  const srv = await (await fetch(URL + 'api/projects/' + pid)).json();
  log('server copy has the fix', JSON.stringify(srv.lines).includes('מתוקן'));
  await pg.getByRole('button', { name: 'המשך להורדה' }).click();
  await pg.getByRole('button', { name: 'הורד סרטון קריוקי MP4' }).click();
  await pg.getByText(/סרטון הקריוקי מוכן להורדה|השרת מרנדר/).first().waitFor({ timeout: 10000 });
  await pg.getByText('סרטון הקריוקי מוכן להורדה').waitFor({ timeout: 90000 });
  const [d] = await Promise.all([pg.waitForEvent('download'), pg.getByRole('button', { name: 'הורד סרטון קריוקי MP4' }).click()]);
  const mp4 = await d.path();
  const dur = parseFloat(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', mp4]).toString());
  log('MP4 downloaded (' + d.suggestedFilename() + ', ' + dur.toFixed(2) + 's)', Math.abs(dur - 14) < 0.7);
  const ass = fs.readFileSync(process.env.LYRA_DATA_DIR + '/projects/' + pid + '/render/karaoke.ass', 'utf8');
  log('render used the edited word', ass.includes('מתוקן'));
  const [st] = await Promise.all([pg.waitForEvent('download'), pg.getByRole('button', { name: /Instrumental/ }).click()]);
  log('instrumental stem downloaded (' + st.suggestedFilename() + ')', st.suggestedFilename().endsWith('.wav'));
  // conflict: another client saves first
  const cur = await (await fetch(URL + 'api/projects/' + pid)).json();
  cur.title = 'שונה מבחוץ';
  await fetch(URL + 'api/projects/' + pid, { method: 'PUT', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ baseRev: cur.serverRev, project: cur }) });
  await pg.getByRole('button', { name: 'תצוגה מקדימה' }).click();
  await pg.getByRole('button', { name: /0:0/ }).first().click();
  await pg.getByLabel('טקסט השורה').fill('שורה ראשונה חדשה'); await pg.getByLabel('טקסט השורה').press('Enter');
  await pg.getByRole('dialog', { name: 'התנגשות גרסאות' }).waitFor({ timeout: 10000 });
  log('real conflict detected (409)', true);
  await pg.getByRole('radio', { name: /הגרסה בשרת/ }).click();
  await pg.getByRole('button', { name: 'טען את הגרסה מהשרת' }).click();
  await pg.waitForTimeout(500);
  log('loaded server version', (await pg.evaluate(() => JSON.parse(localStorage.getItem('lyra.v1.project')).title)) === 'שונה מבחוץ');
  // crash + resume
  await pg.getByRole('button', { name: 'מצב פשוט' }).click();
  await pg.getByRole('button', { name: /1 · מקור/ }).click();
  await pg.getByRole('button', { name: /קריסה בתמלול/ }).click();
  await pg.getByRole('button', { name: /קובץ מקומי/ }).click();
  await pg.locator('input[type=file]').setInputFiles(CLIP);
  await pg.waitForTimeout(500);
  await pg.getByRole('button', { name: 'צור קריוקי' }).click();
  await pg.getByRole('button', { name: 'נסה שוב מהשלב' }).waitFor({ timeout: 60000 });
  log('server crash surfaced', true);
  await pg.getByRole('button', { name: 'נסה שוב מהשלב' }).click();
  await pg.getByRole('heading', { name: 'בדיקה ותיקון מהיר' }).waitFor({ timeout: 90000 });
  log('resumed after crash', true);
  // refresh keeps server project + media
  await pg.reload();
  await pg.getByRole('heading', { name: 'בדיקה ותיקון מהיר' }).waitFor();
  log('restored after refresh', (await pg.locator('audio').count()) === 1);
  if (process.argv[3]) await pg.screenshot({ path: process.argv[3] + '/server-review.png' });
  console.log('errors:', JSON.stringify(errs));
  await b.close();
  process.exit(fails || errs.length ? 1 : 0);
})().catch((e) => { console.error('E2E ERROR', e.message); process.exit(1); });
